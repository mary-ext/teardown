// generates runtime dependency rules from @nubjs/extensions.
//
// usage: pnpm generate:extensions

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

import { parsePackageSpecifier } from '../src/lib/package-name.ts';
import type { PackageExtension } from '../src/npm/lib/package-extensions.ts';

interface Database {
	yarnKeys: string[];
	packageExtensions: Record<
		string,
		{
			dependencies?: Record<string, string>;
			peerDependencies?: Record<string, string>;
			peerDependenciesMeta?: Record<string, { optional?: boolean }>;
		}
	>;
	findings: Array<{ package: string; targets: Array<{ target: string; class: string }> }>;
}

const readJson = (path: string) => JSON.parse(readFileSync(path, 'utf8'));
const byKey = ([a]: [string, unknown], [b]: [string, unknown]) => (a < b ? -1 : 1);

const require = createRequire(import.meta.url);
const { version }: { version: string } = readJson(require.resolve('@nubjs/extensions/package.json'));
const db: Database = readJson(require.resolve('@nubjs/extensions/package-extensions.json'));

// omit type-only imports. retain Yarn rules without findings to classify them.
const typeOnly = new Map<string, Set<string>>();
for (const finding of db.findings) {
	for (const { target, class: kind } of finding.targets) {
		if (kind === 'types') {
			let set = typeOnly.get(finding.package);
			if (set === undefined) {
				typeOnly.set(finding.package, (set = new Set()));
			}
			set.add(target);
		}
	}
}

const yarnKeys = new Set(db.yarnKeys);
const isKept = (selector: string, pkg: string, target: string) => {
	if (target.startsWith('@types/')) {
		return false;
	}
	return yarnKeys.has(selector) || !typeOnly.get(pkg)?.has(target);
};

const pick = <T>(record: Record<string, T> | undefined, keep: (name: string) => boolean) => {
	const entries = Object.entries(record ?? {}).filter(([name]) => keep(name));
	return entries.length > 0 ? Object.fromEntries(entries.toSorted(byKey)) : undefined;
};

const rules: Record<string, PackageExtension[]> = {};
for (const [selector, extension] of Object.entries(db.packageExtensions)) {
	const parsed = parsePackageSpecifier(selector);
	if (parsed === null) {
		throw new Error(`unparseable selector ${selector}`);
	}

	const { name, range } = parsed;
	const keep = (target: string) => isKept(selector, name, target);

	const dependencies = pick(extension.dependencies, keep);
	const peerDependencies = pick(extension.peerDependencies, keep);

	if (dependencies === undefined && peerDependencies === undefined) {
		continue;
	}

	const optionalPeers = Object.keys(peerDependencies ?? {}).filter(
		(target) => extension.peerDependenciesMeta?.[target]?.optional === true,
	);

	(rules[name] ??= []).push({
		range,
		dependencies,
		peerDependencies,
		optionalPeers: optionalPeers.length > 0 ? optionalPeers : undefined,
	});
}

const sorted = Object.fromEntries(Object.entries(rules).toSorted(byKey));

const output = `// generated by scripts/generate-package-extensions.ts from @nubjs/extensions@${version}, do not edit.

import type { PackageExtension } from './package-extensions';

export const packageExtensions: Record<string, PackageExtension[]> = ${JSON.stringify(sorted, null, '\t')};
`;

writeFileSync(new URL('../src/npm/lib/package-extensions-data.ts', import.meta.url), output);

const kept = Object.values(rules).reduce((sum, list) => sum + list.length, 0);
console.log(
	`kept ${kept} of ${Object.keys(db.packageExtensions).length} rules across ${Object.keys(sorted).length} packages`,
);
